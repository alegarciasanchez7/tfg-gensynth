import { useMemo } from 'react';
import { AlertTriangle, Info } from 'lucide-react';
import { Input } from '../ui/input';
import { Badge } from '../ui/badge';
import { INDEX_TOKEN, NAME_TOKEN, buildPatternNames } from '../../core/namingPattern';
import { findBatchNameCollisions, uniqueBatchNames } from '../../core/flowNames';

/** Number of names shown in the live preview. */
const PREVIEW_COUNT = 3;
/** Upper bound of the names checked against `existingNames` on every render. */
const MAX_CHECKED_NAMES = 500;

interface NamingPatternFieldsProps {
  count: string;
  onCountChange: (value: string) => void;
  pattern: string;
  onPatternChange: (value: string) => void;
  /** Value of `${name}` in the preview. */
  itemName: string;
  countLabel: string;
  /** Noun used in the "... and N more" line (e.g. "copies", "flows"). */
  itemsNoun: string;
  /** Called when Enter is pressed in the pattern input. */
  onSubmit?: () => void;
  /** Names already in use: the preview marks the generated names that collide with them or with each other. */
  existingNames?: readonly string[];
  /**
   * What happens to a colliding name: `block` (default) marks it as a conflict (the caller refuses
   * to create it); `rename` shows the name with the " (2)" suffix the Core adds to clones.
   */
  collisionMode?: 'block' | 'rename';
}

interface PreviewName {
  name: string;
  /** Name generated by the pattern when it was renamed (rename mode). */
  original?: string;
  collides: boolean;
}

/**
 * Quantity + naming pattern inputs with `${name}` / `${index}` shortcuts and a live preview.
 * Shared by the Clone dialog and the Repeater (create N flows).
 */
export function NamingPatternFields({
  count,
  onCountChange,
  pattern,
  onPatternChange,
  itemName,
  countLabel,
  itemsNoun,
  onSubmit,
  existingNames,
  collisionMode = 'block',
}: NamingPatternFieldsProps) {
  const total = Number.parseInt(count, 10);
  const { previews, collidingNames } = useMemo(() => {
    if (Number.isNaN(total) || total <= 0) return { previews: [] as PreviewName[], collidingNames: [] as string[] };
    const generated = buildPatternNames(pattern, itemName, existingNames ? Math.min(total, MAX_CHECKED_NAMES) : Math.min(total, PREVIEW_COUNT));
    const collisions = existingNames ? findBatchNameCollisions(generated, existingNames) : new Set<number>();
    const finalNames = existingNames && collisionMode === 'rename' ? uniqueBatchNames(generated, existingNames) : generated;
    return {
      previews: generated.slice(0, PREVIEW_COUNT).map((name, i): PreviewName => ({
        name: finalNames[i],
        original: finalNames[i] === name ? undefined : name,
        collides: collisions.has(i),
      })),
      collidingNames: [...collisions].map((i) => generated[i]),
    };
  }, [total, pattern, itemName, existingNames, collisionMode]);

  return (
    <div className="space-y-6">
      <div className="space-y-2">
        <label htmlFor="naming-pattern-count" className="text-xs text-[var(--c-tx3)] font-mono uppercase tracking-wider">
          {countLabel}
        </label>
        <Input
          id="naming-pattern-count"
          type="number"
          min={1}
          max={50}
          value={count}
          onChange={(e) => onCountChange(e.target.value)}
          className="bg-[var(--c-bg1)] border-[var(--c-br1)] text-[var(--c-tx1)] focus:ring-violet-500"
        />
        <p className="text-[10px] text-[var(--c-tx4)] flex items-center gap-1">
          <Info size={10} /> Max recommended: 50 to ensure system stability.
        </p>
      </div>

      <div className="space-y-2">
        <label htmlFor="naming-pattern-input" className="text-xs text-[var(--c-tx3)] font-mono uppercase tracking-wider">
          Naming Pattern
        </label>
        <Input
          id="naming-pattern-input"
          value={pattern}
          onChange={(e) => onPatternChange(e.target.value)}
          placeholder={`${NAME_TOKEN} ${INDEX_TOKEN}`}
          className="bg-[var(--c-bg1)] border-[var(--c-br1)] text-[var(--c-tx1)] font-mono text-sm focus:ring-violet-500"
          onKeyDown={(e) => {
            if (e.key === 'Enter' && onSubmit) {
              e.preventDefault();
              onSubmit();
            }
          }}
        />
        <div className="flex gap-2 pt-1">
          {[NAME_TOKEN, INDEX_TOKEN].map((token) => (
            <Badge
              key={token}
              variant="outline"
              className="cursor-pointer hover:bg-violet-500/10 border-dashed border-violet-500/30 text-violet-600 dark:text-violet-400 text-[10px]"
              onClick={() => onPatternChange(pattern + token)}
            >
              + {token}
            </Badge>
          ))}
        </div>
        <p className="text-[10px] text-[var(--c-tx4)] flex items-center gap-1">
          <Info size={10} /> {'Use ${index+1} to start counting at 2 (e.g. H${index+1} gives H2, H3...).'}
        </p>
      </div>

      {previews.length > 0 && (
        <div className="p-3 bg-[var(--c-bg1)] rounded-lg border border-[var(--c-br1)] space-y-1.5">
          <span className="text-[10px] text-[var(--c-tx4)] font-mono uppercase tracking-widest">Live Preview</span>
          <div className="space-y-1">
            {previews.map((preview, i) => (
              <div
                key={i}
                className={`text-xs font-mono flex items-center gap-2 ${
                  preview.collides && collisionMode === 'block' ? 'text-red-500' : 'text-[var(--c-tx2)]'
                }`}
              >
                <span className="w-4 h-4 flex items-center justify-center bg-violet-500/10 text-violet-500 rounded text-[9px]">{i + 1}</span>
                {preview.name}
                {preview.collides && (
                  <span className={`text-[10px] ${collisionMode === 'block' ? 'text-red-500' : 'text-amber-500'}`}>
                    {preview.original ? `(renamed: "${preview.original}" already exists)` : '(already exists)'}
                  </span>
                )}
              </div>
            ))}
            {total > PREVIEW_COUNT && (
              <div className="text-[10px] text-[var(--c-tx4)] italic pl-6">
                ... and {total - PREVIEW_COUNT} more {itemsNoun}
              </div>
            )}
          </div>
          {collidingNames.length > 0 && (
            <p
              role={collisionMode === 'block' ? 'alert' : 'status'}
              className={`text-[10px] flex items-start gap-1 pt-1 ${collisionMode === 'block' ? 'text-red-500' : 'text-amber-500'}`}
            >
              <AlertTriangle size={10} className="shrink-0 mt-0.5" />
              <span>
                {collidingNames.length === 1 ? '1 name is' : `${collidingNames.length} names are`} already used
                {' '}({collidingNames.slice(0, PREVIEW_COUNT).map((name) => `"${name}"`).join(', ')}
                {collidingNames.length > PREVIEW_COUNT ? ', ...' : ''})
                {collisionMode === 'rename'
                  ? ': a suffix such as " (2)" is added to keep the names unique.'
                  : ': change the naming pattern or the base name.'}
              </span>
            </p>
          )}
        </div>
      )}
    </div>
  );
}
